using System.Text.Json.Serialization;

namespace BillCollection.Models.BREB
{
    public class BREBBillingInfoResponse
    {
        [JsonConverter(typeof(BREBFlexibleStringConverter))]
        public string? SMSAccountNo { get; set; }

        public string? AccountName { get; set; }

        public string? RefNo { get; set; }

        public string? PaymentTimestamp { get; set; }

        public string? DueType { get; set; }

        public string? BillMonth { get; set; }

        public decimal Amount { get; set; }

        public decimal Vat { get; set; }

        [JsonConverter(typeof(BREBFlexibleStringConverter))]
        public string? ExpiresIn { get; set; }

        public string? Message { get; set; }

        /// <summary>Generated by us when the bill is queried (not part of BREB's response).</summary>
        [JsonIgnore]
        public string? PayerTransactionId { get; set; }
    }
}